/**
 * Line icons, drawn inline.
 *
 * SVG rather than unicode glyphs: those render at a different size and weight in every font —
 * "▸" and "▾" come out as thin, off-centre marks on Windows — and an icon font or package
 * would be a dependency for a dozen paths.
 *
 * Every icon is decorative (`aria-hidden`). Meaning is always carried by the text beside it
 * or by the control's accessible name, on the same rule as every chip in this console.
 */

type IconProps = { size?: number; className?: string };

function Svg({
  size = 16,
  className,
  children,
}: IconProps & { children: React.ReactNode }) {
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={2}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      focusable="false"
      className={className ? `icon ${className}` : "icon"}
    >
      {children}
    </svg>
  );
}

